"""Preserve literal whitespace through Excel open/save, without changing facts.

artifact-tool exports strings without xml:space; Excel may trim indentation.
Patch only text nodes in the newly authored XLSX package before native Excel.
"""
from pathlib import Path
import argparse,zipfile,os
from lxml import etree

def preserve(path):
    path=Path(path);temp=path.with_suffix('.whitespace.tmp');count=0
    try:
        with zipfile.ZipFile(path) as src,zipfile.ZipFile(temp,'w',zipfile.ZIP_DEFLATED) as dst:
            for info in src.infolist():
                content=src.read(info.filename)
                if info.filename=='xl/sharedStrings.xml' or info.filename.startswith('xl/worksheets/sheet') and info.filename.endswith('.xml'):
                    root=etree.fromstring(content)
                    ns='{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'
                    for cell in root.iter(ns+'c'):
                        value=cell.find(ns+'v')
                        # Non-formula t=str exports use v rather than a string t.
                        # Inline strings have the supported xml:space contract.
                        if cell.get('t')=='str' and cell.find(ns+'f') is None and value is not None and value.text and (value.text[0].isspace() or value.text[-1].isspace()):
                            text=value.text;cell.remove(value);cell.set('t','inlineStr')
                            inline=etree.SubElement(cell,ns+'is');etree.SubElement(inline,ns+'t').text=text
                    for t in root.iter('{http://schemas.openxmlformats.org/spreadsheetml/2006/main}t'):
                        if t.text and (t.text[0].isspace() or t.text[-1].isspace()):
                            t.set('{http://www.w3.org/XML/1998/namespace}space','preserve');count+=1
                    content=etree.tostring(root,encoding='UTF-8',xml_declaration=True)
                dst.writestr(info,content)
        os.replace(temp,path)
    finally:
        if temp.exists():temp.unlink()
    return count

def install_formulas(path,plan):
    """Replace planned formula placeholders with OOXML formula cells.

    This bounded post-export step avoids author-tool eager evaluation of a large
    history. Every formula is generated by the planner, independently checked,
    and then calculated in native Excel; never use imported source text as code.
    """
    path=Path(path);temp=path.with_suffix('.formulas.tmp');count=0
    ns='{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'
    with zipfile.ZipFile(path) as src,zipfile.ZipFile(temp,'w',zipfile.ZIP_DEFLATED) as dst:
        for info in src.infolist():
            content=src.read(info.filename)
            for i,(name,spec) in enumerate(plan['sheets'].items(),1):
                if info.filename==f'xl/worksheets/sheet{i}.xml':
                    root=etree.fromstring(content);cells={c.get('r'):c for c in root.findall('.//'+ns+'c')}
                    planned={c['address'] for c in spec['cells'] if 'formula' in c}
                    # Imported template ratio formulas may survive author-tool
                    # content clearing. They are scaffold, never output facts.
                    for addr,cell in cells.items():
                        if cell.find(ns+'f') is not None and addr not in planned:
                            for child in list(cell):cell.remove(child)
                            cell.attrib.pop('t',None)
                    for item in spec['cells']:
                        if 'formula' not in item:continue
                        cell=cells[item['address']]
                        for child in list(cell):cell.remove(child)
                        cell.attrib.pop('t',None);etree.SubElement(cell,ns+'f').text=item['formula'][1:];count+=1
                    content=etree.tostring(root,encoding='UTF-8',xml_declaration=True)
            dst.writestr(info,content)
    os.replace(temp,path)
    return count

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('xlsx');args=p.parse_args();print('Preserved text nodes:',preserve(args.xlsx))
